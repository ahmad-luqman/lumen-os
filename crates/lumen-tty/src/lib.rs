//! Terminal line discipline modelled on n_tty, separate from `lumen-term`.
//!
//! Construction is fallible. All subsequent operations use fixed input
//! storage and a caller-supplied output sink, with no allocation. Echo units
//! are atomic; insufficient sink room drops that unit and the rest of that
//! call's echo, reported as `Echo::Truncated`. Writes instead return the
//! consumed prefix for retry. Only accepted output changes the column.
//!
//! Known differences from n_tty:
//! - IMAXBEL rings BEL on overflow (Linux ignores it); echo loss is reported
//!   as an atomic prefix instead of using Linux's internal echo ring.
//! - Columns are tracked with OPOST off. Tab erase uses width recorded at
//!   echo time; Linux recomputes from canon_column, differing when write
//!   output lands mid-line. Erase uses actual echoed widths: typing with
//!   ECHO off then enabling it does not erase unseen characters; disabling
//!   ECHO before erasure suppresses the rubout, leaving drawn text visible.
//! - ERASE at exactly 4096 bytes leaves 4095. Linux first evicts the overflow
//!   byte, then erases, leaving 4094. A full buffer with a completed record
//!   still processes signals and editing here; Linux consumes nothing.
//! - Raw-to-canonical switching returns a trailing NUL as data. Linux drops
//!   a flagged __DISABLED_CHAR; a lone NUL then reads as EOF.
//! - Full buffers drop bytes forced by the driver where Linux leaves them
//!   upstream. Every driver's backpressure must obey accepts. Canonical
//!   overflow without completed records is consumed and reports Replaced.
//!
//! IXON/IXOFF, parity, baud-rate effects and TIOCSTI are outside scope, as are
//! IUCLC, OLCUC, ECHOPRT, XTABS, EXTPROC, PARMRK/INPCK and IXANY. VSTART/VSTOP
//! arrive as data. Unsupported bits are preserved in the termios value.
//! A byte cannot distinguish BREAK from NUL; drivers supply receive_break.
//! The kernel owns clocks, drain waits, signals and wake-all wait queues.

#![no_std]
#![forbid(unsafe_code)]

