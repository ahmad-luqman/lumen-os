"""Generate docs/STATUS.md from test results (hard rule 10: one status doc, from tests).

Inputs (written by `make test`):
  build/test-results/scenarios.xml   JUnit XML from tests/scenarios
  build/test-results/harness.xml     JUnit XML from tests/harness
  build/test-results/ktest.tap       TAP from the in-kernel test run
  build/test-results/audit.json      result of `make audit`
  build/test-results/cargo.json      result of `cargo test` per crate

and tests/features/*.toml, which map each feature to the tests that prove it.
A feature is "passing" only if every test pattern matched at least one test
and all matched tests passed.

`--check` is the CI gate: it fails if any feature is not passing. It does not
compare against the committed docs/STATUS.md, so parallel PRs never conflict
over generated text. The committed file is refreshed with `make status` on
main; because every merged commit passed the gate, it can lag behind by
missing new features but can never claim something that is broken.
"""

from __future__ import annotations

import json
import os
import re
import sys
import tomllib
import xml.etree.ElementTree as ET
from pathlib import Path

from . import BUILD_DIR, REPO_ROOT, tap

RESULTS = BUILD_DIR / "test-results"
STATUS_MD = REPO_ROOT / "docs" / "STATUS.md"
FEATURES_DIR = REPO_ROOT / "tests" / "features"

ICON = {"pass": "passing", "fail": "**FAILING**", "missing": "not run"}


def junit_results(path: Path, prefix: str) -> dict[str, bool]:
    out: dict[str, bool] = {}
    if not path.exists():
        return out
    for case in ET.parse(path).iter("testcase"):
        module = case.get("classname", "").rsplit(".", 1)[-1]
        name = case.get("name", "")
        failed = any(case.find(t) is not None for t in ("failure", "error"))
        skipped = case.find("skipped") is not None
        if not skipped:
            out[f"{prefix}:{module}::{name}"] = not failed
    return out


def collect_results() -> dict[str, bool]:
    results: dict[str, bool] = {}
    results |= junit_results(RESULTS / "scenarios.xml", "scenario")
    results |= junit_results(RESULTS / "harness.xml", "harness")
    tap_file = RESULTS / "ktest.tap"
    if tap_file.exists():
        report = tap.parse(tap_file.read_text())
        for c in report.cases:
            results[f"ktest:{c.name}"] = c.ok
    for name, file in (("audit", "audit.json"), ("cargo", "cargo.json")):
        f = RESULTS / file
        if f.exists():
            for key, ok in json.loads(f.read_text()).items():
                results[f"{name}:{key}"] = bool(ok)
    return results


def pattern_matches(pattern: str, test_id: str) -> bool:
    """`*` is the only wildcard (brackets are literal: pytest IDs use `[param]`)."""
    rx = "^" + re.escape(pattern).replace(r"\*", ".*") + "$"
    return re.match(rx, test_id) is not None


def feature_status(patterns: list[str], results: dict[str, bool]) -> str:
    any_missing = False
    for pat in patterns:
        matched = [ok for tid, ok in results.items() if pattern_matches(pat, tid)]
        if not matched:
            any_missing = True
        elif not all(matched):
            return "fail"
    return "missing" if any_missing else "pass"


def load_features() -> list[dict]:
    features: list[dict] = []
    for path in sorted(FEATURES_DIR.glob("*.toml")):
        for f in tomllib.loads(path.read_text()).get("feature", []):
            features.append({**f, "area": path.stem})
    return features


def evaluate(results: dict[str, bool]) -> list[tuple[dict, str]]:
    return [(f, feature_status(f["tests"], results)) for f in load_features()]


def render(evaluated: list[tuple[dict, str]]) -> str:
    rows = []
    for f, st in evaluated:
        tests = "<br>".join(f"`{t}`" for t in f["tests"])
        rows.append(f"| {f['milestone']} | {f['area']} | {f['name']} | {ICON[st]} | {tests} |")
    lines = [
        "# Lumen status",
        "",
        "<!-- Generated by `make status` from test results. Do not edit by hand. -->",
        "",
        "Only features with automated tests appear here (hard rule 1). Planned work",
        "is in [ROADMAP.md](ROADMAP.md). CI fails any PR that breaks a listed feature;",
        "this file is refreshed on main with `make test status`.",
        "",
        "| Milestone | Area | Feature | Status | Tests |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Known gaps (temporary exceptions to the hard rules)",
        "",
        "- Rule 4 (stacks from the allocator with guard pages): the boot stack and",
        "  the IST stacks are static and unguarded until the M1 allocator exists (#6).",
        "",
    ]
    return "\n".join(lines)


def run_status(write: bool, check: bool) -> int:
    results = collect_results()
    evaluated = evaluate(results)
    text = render(evaluated)
    if summary := os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(summary, "a") as fh:
            fh.write(text + "\n")
    if write:
        STATUS_MD.write_text(text)
        print(f"status: wrote {STATUS_MD.relative_to(REPO_ROOT)}")
    bad = [(f, st) for f, st in evaluated if st != "pass"]
    for f, st in bad:
        print(f"status: {ICON[st]}: [{f['area']}] {f['name']}", file=sys.stderr)
        for pat in f["tests"]:
            matched = {t: ok for t, ok in results.items() if pattern_matches(pat, t)}
            if not matched:
                print(f"    {pat}: no test ran with this id", file=sys.stderr)
            for t, ok in matched.items():
                if not ok:
                    print(f"    {t}: failed", file=sys.stderr)
    if check:
        if bad:
            print(f"status: {len(bad)} feature(s) not passing", file=sys.stderr)
            return 1
        print(f"status: all {len(evaluated)} features passing")
    return 0
